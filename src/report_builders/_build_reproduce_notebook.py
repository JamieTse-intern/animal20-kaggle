# ============================================================== 7. blending
md(r"""
## 7. Temperature-matched blending — the two final picks

Two models are blended by **matching their sharpness, then averaging with equal weight**.

The reason sharpness needs matching: a model with higher mean top-1 confidence dominates the
`argmax` of a plain average regardless of whether it is more often right. So for each member a
temperature `T` is solved by bisection such that `softmax(log p / T)` has the *same* mean top-1
confidence as the reference member, and only then are the members averaged equally.

**No parameter here is fitted on the leaderboard.** Every temperature is solved from the
models' own confidences on the test set, and the weights are fixed at equal. This matters
because the ranking is on a private split — weights tuned against public feedback would overfit
the half of the data that does not count.

| pick | members | public LB |
|---|---|---|
| 1 | DINOv2 ViT-L pseudo1 + **EVA-02 Large** pseudo1 | **0.98196** |
| 2 | DINOv2 ViT-L pseudo1 + DINOv3 ViT-L pseudo1 | 0.98132 |

The two share the DINOv2 model and differ in the second member, which comes from a different
pretraining family in each. Their public scores are a statistical tie (Δ 0.064pt on 80 differing
rows), so the higher one is pick 1. Because the private split is a random 20% of the same test
set, the second pick is not a hedge against some hidden weakness; its value is a real chance of
coming out ahead on 2,336 images, which is largest for a near-tied file that still differs on a
meaningful number of rows.
""")

code(r'''
EPSILON = 1e-12


def normalise(p):
    p = np.asarray(p, dtype=np.float64)
    return p / p.sum(axis=1, keepdims=True)


def sharpen(p, T):
    """softmax(log p / T): T < 1 sharpens, T > 1 flattens."""
    z = np.log(np.clip(p, EPSILON, None)) / T
    z -= z.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def fit_temperature(p, target_confidence, low=0.05, high=20.0, iterations=200):
    """Solve for T with mean top-1 confidence == target. Monotone in T, so bisect."""
    for _ in range(iterations):
        mid = 0.5 * (low + high)
        if sharpen(p, mid).max(axis=1).mean() > target_confidence:
            low = mid
        else:
            high = mid
    return 0.5 * (low + high)


def temperature_matched_blend(member_probabilities):
    """Match every member to the FIRST member's sharpness, then average equally."""
    members = [normalise(p) for p in member_probabilities]
    target = members[0].max(axis=1).mean()
    matched, temperatures = [], []
    for i, p in enumerate(members):
        T = 1.0 if i == 0 else fit_temperature(p, target)
        temperatures.append(T)
        matched.append(p if T == 1.0 else sharpen(p, T))
    return sum(matched) / len(matched), temperatures


def load_probabilities(tag):
    path = OUTPUTS_DIR / f'{tag}_test_prob.npy'
    assert path.is_file(), (
        f'{path} not found. In cached mode, upload model_outputs.zip and extract it, '
        f'or run this notebook inside the project repository.'
    )
    probabilities = normalise(np.load(path))
    assert probabilities.shape == (EXPECTED_TEST_IMAGES, len(EXPECTED_CLASS_NAMES))
    return probabilities


PICKS = {
    'pick 1': ('submission_ens_V2PEVAPtemp.csv', ['dinov2vitlps1', 'eva02lps1'], 0.98196),
    'pick 2': ('submission_ens_V2PV3Ptemp.csv', ['dinov2vitlps1', 'dinov3vitlps1'], 0.98132),
}

blended = {}
for name, (filename, tags, public) in PICKS.items():
    members = [load_probabilities(t) for t in tags]
    probabilities, temperatures = temperature_matched_blend(members)
    blended[name] = probabilities
    reference = normalise(members[0]).max(axis=1).mean()
    print(f'{name} -> {filename}   (public LB {public:.5f})')
    for tag, T, member in zip(tags, temperatures, members):
        print(f'    {tag:16s} T = {T:.4f}   mean top-1 confidence '
              f'{member.max(axis=1).mean():.4f} -> {reference:.4f}')
    print(f'    blended mean top-1 confidence {probabilities.max(axis=1).mean():.4f}')
    if name != 'pick 1':
        differing = int((probabilities.argmax(1) != blended['pick 1'].argmax(1)).sum())
        print(f'    differs from pick 1 on {differing} of {EXPECTED_TEST_IMAGES:,} rows')
    print()
''')

